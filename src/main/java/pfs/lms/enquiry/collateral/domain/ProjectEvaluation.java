package pfs.lms.enquiry.collateral.domain;

import com.fasterxml.jackson.annotation.JsonIgnore;
import pfs.lms.enquiry.domain.AggregateRoot;
import pfs.lms.enquiry.domain.LoanApplication;

import javax.persistence.Column;
import javax.persistence.Entity;
import javax.persistence.FetchType;
import javax.persistence.JoinColumn;
import javax.persistence.ManyToOne;
import javax.persistence.Table;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.UUID;

/**
 * Project (collateral) evaluation of a loan: a row of SAP table ZLMS_COLL_EVAL ("Project Collateral Valuation
 * History", tab Project(Coll.) Valuation of the loan contract), 1:N with the loan. All SAP columns are kept except the
 * client (MANDT) and the SAP audit fields (CREATED_AT/BY, CHANGED_AT/BY), which the portal
 * keeps in {@link AggregateRoot}. SAP's gateway service is ZPFS_LMS_COLLATERAL_SRV, entity set
 * ProjectEvaluationSet. The entity's own id ({@link #getId()}) is the
 * portal id in SAP (PTL_ID), so there is no separate portal id field: the SAP integration sends the id as PtlId,
 * and SAP finds the row by it. SAP's own row GUID (ID), generated by SAP on create, is kept in {@link #sapId}.
 */
@Entity
@Table(name = "collateral_project_evaluation")
public class ProjectEvaluation extends AggregateRoot<ProjectEvaluation> {

    @JsonIgnore
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "loan_application_id", nullable = false)
    private LoanApplication loanApplication;

    /** Company Code */
    @SapField("BUKRS")
    @Column(length = 4)
    private String companyCode;

    /** Archiving Category Indicator */
    @SapField("SARCHIV")
    @Column(length = 1)
    private String archivingCategory;

    /** Contract Number */
    @SapField("RANL")
    @Column(length = 13)
    private String contractNumber;

    /** Line Item Number (NUMC 6), 1, 2, 3 … per loan */
    @SapField("ITEM_NO")
    private Integer itemNumber;

    /** Major Collateral Type (1 Others, 2 CRE (Commercial Real Estate), 3 CRE-RH (Residential Housing)) */
    @SapField("MAJOR_COLL_TYPE")
    @Column(length = 2)
    private String majorCollateralType;

    /** Valuation By (ZDE_PROJ_VAL_BY: 1 Credit Team, 2 Valuer) */
    @SapField("VALUATION_BY")
    @Column(length = 1)
    private String valuationBy;

    /** Date on which the valuation was performed */
    @SapField("VAL_DATE")
    private LocalDate valuationDate;

    /** Total Loan Asset (CURR 15,2) */
    @SapField("TOTAL_ASSET")
    @Column(precision = 15, scale = 2)
    private BigDecimal totalLoanAsset;

    /** Total Current Liabilities (CURR 17,2) */
    @SapField("TOTAL_CURR_LIAB")
    @Column(precision = 17, scale = 2)
    private BigDecimal totalCurrentLiabilities;

    /** Net (Valuation Amount) (CURR 17,2) */
    @SapField("NET_VAL_AMT")
    @Column(precision = 17, scale = 2)
    private BigDecimal netValuationAmount;

    /** Currency of the amounts */
    @SapField("VAL_CURR")
    @Column(length = 5)
    private String currency;

    /** Remarks */
    @SapField("REMARKS")
    @Column(length = 60)
    private String remarks;

    /** Portal Id of the sanction stage */
    @SapField("PTL_SANC_STAGE_ID")
    @Column(length = 40)
    private String sanctionStagePortalId;

    /** SAP row GUID (ID, RAW 16 as 32 hex characters) */
    @SapField("ID")
    @Column(length = 32)
    private String sapId;

    /** Source of Entry */
    @SapField("SOURCEOFENTRY")
    @Column(length = 32)
    private String sourceOfEntry;

    public ProjectEvaluation() {
    }

    public UUID getLoanApplicationId() {
        return loanApplication != null ? loanApplication.getId() : null;
    }

    public LoanApplication getLoanApplication() { return loanApplication; }
    public void setLoanApplication(LoanApplication loanApplication) { this.loanApplication = loanApplication; }
    public String getCompanyCode() { return companyCode; }
    public void setCompanyCode(String companyCode) { this.companyCode = companyCode; }
    public String getArchivingCategory() { return archivingCategory; }
    public void setArchivingCategory(String archivingCategory) { this.archivingCategory = archivingCategory; }
    public String getContractNumber() { return contractNumber; }
    public void setContractNumber(String contractNumber) { this.contractNumber = contractNumber; }
    public Integer getItemNumber() { return itemNumber; }
    public void setItemNumber(Integer itemNumber) { this.itemNumber = itemNumber; }
    public String getMajorCollateralType() { return majorCollateralType; }
    public void setMajorCollateralType(String majorCollateralType) { this.majorCollateralType = majorCollateralType; }
    public String getValuationBy() { return valuationBy; }
    public void setValuationBy(String valuationBy) { this.valuationBy = valuationBy; }
    public LocalDate getValuationDate() { return valuationDate; }
    public void setValuationDate(LocalDate valuationDate) { this.valuationDate = valuationDate; }
    public BigDecimal getTotalLoanAsset() { return totalLoanAsset; }
    public void setTotalLoanAsset(BigDecimal totalLoanAsset) { this.totalLoanAsset = totalLoanAsset; }
    public BigDecimal getTotalCurrentLiabilities() { return totalCurrentLiabilities; }
    public void setTotalCurrentLiabilities(BigDecimal totalCurrentLiabilities) { this.totalCurrentLiabilities = totalCurrentLiabilities; }
    public BigDecimal getNetValuationAmount() { return netValuationAmount; }
    public void setNetValuationAmount(BigDecimal netValuationAmount) { this.netValuationAmount = netValuationAmount; }
    public String getCurrency() { return currency; }
    public void setCurrency(String currency) { this.currency = currency; }
    public String getRemarks() { return remarks; }
    public void setRemarks(String remarks) { this.remarks = remarks; }
    public String getSanctionStagePortalId() { return sanctionStagePortalId; }
    public void setSanctionStagePortalId(String sanctionStagePortalId) { this.sanctionStagePortalId = sanctionStagePortalId; }
    public String getSapId() { return sapId; }
    public void setSapId(String sapId) { this.sapId = sapId; }
    public String getSourceOfEntry() { return sourceOfEntry; }
    public void setSourceOfEntry(String sourceOfEntry) { this.sourceOfEntry = sourceOfEntry; }
}
